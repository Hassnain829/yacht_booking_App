/** PascalCase export name → the kebab-case name used in data-lucide="…" (Building2 → building-2). */
export function toIconName(exportName) {
    return exportName
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([a-zA-Z])(\d)/g, '$1-$2')
        .toLowerCase();
}

/** Every icon name we support, e.g. ['anchor', 'arrow-left', …]. */
export const iconNames = Object.keys(icons).map(toIconName).sort();

/** Replace <i data-lucide="…"> placeholders inside `root` with SVGs. Safe to call repeatedly. */
export function renderIcons(root = document) {
    createIcons({ icons, root, attrs: { 'aria-hidden': 'true', focusable: 'false' } });
}
